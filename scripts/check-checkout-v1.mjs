import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";
const folder="docs/design/checkout-v1/";
const model=readFileSync(folder+"model.js","utf8");
const m=vm.runInNewContext(model+"\nDemo");
assert.equal(m.locate("").fee,null);
assert.equal(m.locate("Atlanta").fee,null);
assert.equal(m.locate("Newnan").fee,null);
assert.equal(m.locate("30269").fee,0);
assert.equal(m.locate("99999").fee,null);
assert.equal(m.validDate("2026-02-30"),false);
assert.equal(m.validDate("2026-12-07"),true);
const s={size:11,location:"30269",days:3,date:m.dates[0]};
assert.equal(m.price(s).total,325);
assert.equal(m.canReview(s),true);
for(const days of [0,2,4,30,31])assert.equal(m.canReview({...s,days}),false);
assert.equal(m.price({...s,days:4}).total,null);
assert.equal(m.price({...s,days:31}).quoteOnly,true);
assert.equal(m.canReview({...s,location:"Atlanta"}),false);
assert.equal(m.canReview({...s,date:m.dates[1]}),false);
assert.equal(m.canReview({...s,size:21,date:m.dates[2]}),false);
assert.equal(m.recommendation("heavy"),null);
assert.equal(m.recommendation("renovation"),16);
const html=readFileSync(folder+"index.html","utf8");
for(const script of html.matchAll(/<script>([\s\S]*?)<\/script>/g))new vm.Script(script[1]);
assert.ok(html.includes("connect-src 'none'"));
assert.ok(html.includes("form-action 'none'"));
assert.ok(!/\bfetch\s*\(|XMLHttpRequest|localStorage|sessionStorage|https?:\/\//.test(html+model));
assert.ok(html.includes("Simulate payment"));
assert.ok(html.includes("No payment, receipt, email or text was sent."));
console.log("Checkout V1 fixture, invalid date, fee, duration, availability and isolation checks passed.");